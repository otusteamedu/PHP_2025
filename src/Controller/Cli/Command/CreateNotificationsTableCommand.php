<?php

declare(strict_types=1);

namespace App\Controller\Cli\Command;

use App\Core\Database\Connection\PDOWrapper;
use App\Domain\OrderNotification\ValueObject\Order\OrderEvent;
use App\Domain\OrderNotification\ValueObject\Task\NotificationChannel;
use App\Domain\OrderNotification\ValueObject\Task\TaskStatus;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;

#[AsCommand('db:table:create:notifications')]
class CreateNotificationsTableCommand extends Command
{
    private const string TABLE_NAME = 'notification_tasks';
    private const array ENUM_TYPES = [
        'order_event' => OrderEvent::class,
        'task_status' => TaskStatus::class,
        'notification_channel' => NotificationChannel::class,
    ];

    public function __construct(
        private readonly PDOWrapper $pdoWrapper,
    ) {
        parent::__construct();
    }

    protected function configure(): void
    {
        $this
            ->addOption(
                'force',
                'f',
                InputOption::VALUE_NONE,
                'Пересоздать таблицу и enum-типы, если они уже существуют.',
            );
    }

    public function __invoke(InputInterface $input, OutputInterface $output): int
    {
        $force = $input->getOption('force');
        $pdo = $this->pdoWrapper->getHandler();

        if ($force) {
            $this->dropTable($pdo, $output);
            $this->dropEnumTypes($pdo, $output);
        }

        $this->createEnumTypes($pdo, $output);
        $this->createTable($pdo, $output);

        return Command::SUCCESS;
    }

    private function createTable(\PDO $pdo, OutputInterface $output): void
    {
        $columnDefinitionList = [
            'id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY',
            'order_id BIGINT NOT NULL',
            'order_event order_event NOT NULL',
            'task_status task_status NOT NULL',
            'notification_channel notification_channel NOT NULL',
            'recipient VARCHAR(100) NOT NULL',
            'failure_reason TEXT DEFAULT NULL',
            'attempts INT NOT NULL DEFAULT 0',
            'created_at TIMESTAMP(0) NOT NULL',
            'processed_at TIMESTAMP(0) DEFAULT NULL',
            'CHECK (processed_at IS NULL OR processed_at >= created_at)',
        ];

        $sql = sprintf(
            'CREATE TABLE IF NOT EXISTS %s (%s)',
            self::TABLE_NAME,
            implode(', ', $columnDefinitionList),
        );

        $pdo->exec($sql);
        $output->writeln(sprintf('Таблица %s создана.', self::TABLE_NAME));
    }

    private function createEnumTypes(\PDO $pdo, OutputInterface $output): void
    {
        foreach (self::ENUM_TYPES as $type => $enumClass) {
            if ($this->enumTypeExists($pdo, $type)) {
                continue;
            }

            $values = implode(', ', array_map(
                static fn(\BackedEnum $case) => "'{$case->value}'",
                $enumClass::cases(),
            ));

            $pdo->exec(sprintf('CREATE TYPE %s AS ENUM (%s)', $type, $values));
            $output->writeln(sprintf('Enum-тип %s (%s) создан.', $type, $values));
        }
    }

    private function enumTypeExists(\PDO $pdo, string $type): bool
    {
        $stmt = $pdo->prepare('SELECT 1 FROM pg_type WHERE typname = :type');
        $stmt->execute([':type' => $type]);

        return (bool) $stmt->fetch();
    }

    private function dropTable(\PDO $pdo, OutputInterface $output): void
    {
        $pdo->exec(sprintf('DROP TABLE IF EXISTS %s', self::TABLE_NAME));
        $output->writeln(sprintf('Таблица %s удалена.', self::TABLE_NAME));
    }

    private function dropEnumTypes(\PDO $pdo, OutputInterface $output): void
    {
        foreach (array_keys(self::ENUM_TYPES) as $type) {
            $pdo->exec(sprintf('DROP TYPE IF EXISTS %s', $type));
            $output->writeln(sprintf('Enum-тип %s удалён.', $type));
        }
    }
}
