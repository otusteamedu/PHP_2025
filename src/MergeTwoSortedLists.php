<?php

namespace Igor\Test;

/**
 * Решение задачи: Merge Two Sorted Lists
 * 
 * Задача: Объединить два отсортированных связанных списка в один отсортированный список.
 * 
 * @link https://leetcode.com/problems/merge-two-sorted-lists/
 */
class MergeTwoSortedLists
{
    /**
     * Объединяет два отсортированных связанных списка в один отсортированный список.
     * 
     * Алгоритм:
     * 1. Создаем фиктивный узел (dummy) для упрощения логики
     * 2. Используем указатель current для построения результирующего списка
     * 3. Сравниваем значения узлов из обоих списков
     * 4. Добавляем меньший узел к результату и перемещаем указатель
     * 5. После завершения одного из списков, добавляем оставшиеся узлы
     * 
     * Временная сложность: O(m + n), где m и n - длины списков
     * Пространственная сложность: O(1) - используем только указатели
     * 
     * @param ListNode|null $list1 Первый отсортированный список
     * @param ListNode|null $list2 Второй отсортированный список
     * @return ListNode|null Объединенный отсортированный список
     */
    public function mergeTwoLists(?ListNode $list1, ?ListNode $list2): ?ListNode
    {
        // Создаем фиктивный узел для упрощения логики
        // Это позволяет избежать проверки на пустой результат при первом добавлении
        $dummy = new ListNode();
        $current = $dummy;

        // Пока оба списка не пусты, сравниваем их элементы
        while ($list1 !== null && $list2 !== null) {
            if ($list1->val <= $list2->val) {
                // Элемент из первого списка меньше или равен
                $current->next = $list1;
                $list1 = $list1->next;
            } else {
                // Элемент из второго списка меньше
                $current->next = $list2;
                $list2 = $list2->next;
            }
            $current = $current->next;
        }

        // Добавляем оставшиеся элементы из непустого списка
        // Если один из списков закончился, просто присоединяем остаток другого
        $current->next = $list1 !== null ? $list1 : $list2;

        // Возвращаем результат, пропуская фиктивный узел
        return $dummy->next;
    }
}
