#!/bin/bash

# 1. Проверка, что передан ровно один аргумент
if [ $# -ne 1 ]; then
    echo "Ошибка: необходимо передать один аргумент (например, '1.5-3')" >&2
    exit 1
fi

input="$1"

# Регулярное выражение для проверки формата: число1 (знак) число2
# Поддерживает целые и дробные (через точку)
pattern='^([0-9]+(\.[0-9]+)?)([-+])([0-9]+(\.[0-9]+)?)$'

if [[ "$input" =~ $pattern ]]; then
    # 2. Извлекаем компоненты (для наглядности проверки)
    num1="${BASH_REMATCH[1]}"
    sign="${BASH_REMATCH[3]}"
    num2="${BASH_REMATCH[4]}"
    
    # 3. Дополнительная проверка на валидность чисел (уже покрыта регуляркой выше, 
    # но здесь можно добавить логику, если нужно)
    
    # Вычисляем через awk
    result=$(awk "BEGIN { print $num1 $sign $num2 }")
    echo "$result"
else
    echo "Ошибка: неверный формат или невалидные числа в '$input'" >&2
    echo "Пример: 1.5-3 или 10+5.2" >&2
    exit 1
fi
