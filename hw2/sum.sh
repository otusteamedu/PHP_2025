#!/bin/bash

# Проверка, что передан один аргумент
if [ $# -ne 1 ]; then
    echo "Ошибка: необходимо передать один аргумент в формате 'число1число2'" >&2
    echo "Использование: $0 <число1><число2>" >&2
    echo "Пример: $0 1.5-3" >&2
    exit 1
fi

# Получаем входную строку
input="$1"

# Пытаемся разбить строку на два числа
# Ищем минус или плюс в середине строки
if [[ "$input" =~ ^([0-9.]+)([-+])([0-9.]+)$ ]]; then
    num1="${BASH_REMATCH[1]}"
    sign="${BASH_REMATCH[2]}"
    num2="${BASH_REMATCH[3]}"
    
    # Если знак минус, делаем второе число отрицательным
    if [ "$sign" = "-" ]; then
        num2="-$num2"
    fi
else
    echo "Ошибка: неверный формат '$input'" >&2
    echo "Используйте формат: число1число2" >&2
    echo "Пример: 1.5-3 или 10+5" >&2
    exit 1
fi

# Проверяем, что оба числа валидны
if ! [[ "$num1" =~ ^-?[0-9]+([.][0-9]+)?$ ]] || ! [[ "$num2" =~ ^-?[0-9]+([.][0-9]+)?$ ]]; then
    echo "Ошибка: невалидные числа" >&2
    exit 1
fi

# Вычисляем сумму
result=$(echo "$num1 + $num2" | bc)
echo "$result"